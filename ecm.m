function [dx_dt] = ecm (~, x, p)
%------------------------------------
a_1 = p(1);
a_2 = p(2);
b_1 = p(3);
b_2 = p(4);
xi = p(5);
lambda = p(6);
c_1 = p(7);
c_2 = p(8);
mu_1 = p(9);
mu_2 = p(10);
%------------------------------------
s = x(1);
i_1 = x(2);
i_2 = x(3);
%------------------------------------
f_1 = a_1*s^xi*i_1/(1 + b_1*i_1);
f_2 = a_2*s^xi*i_2/(1 + b_2*i_2);
%------------------------------------
h_11 = c_1*i_1^mu_1;
h_21 = c_2*i_2^mu_2;
%------------------------------------
s_dot = - f_1 - f_2 + lambda*(1-s);
i_1_dot = f_1 - lambda*i_1 - h_11;
i_2_dot = f_2 - lambda*i_2 - h_21;
%------------------------------------
dx_dt = [s_dot; i_1_dot; i_2_dot];
%------------------------------------
end
